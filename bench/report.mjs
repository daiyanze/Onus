#!/usr/bin/env node
// Writes bench/RESULTS.md from every result file under bench/results.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import { BENCH } from "./lib/workspace.mjs";

const { values: o } = parseArgs({
  options: {
    results: { type: "string", default: join(BENCH, "results") },
    out: { type: "string", default: join(BENCH, "RESULTS.md") },
  },
});

const walk = (d) => readdirSync(d).flatMap((n) => {
  const p = join(d, n);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith(".json") ? [p] : [];
});
const results = walk(o.results).map((f) => ({ file: relative(BENCH, f), ...JSON.parse(readFileSync(f, "utf8")) }));

const groups = new Map();
for (const r of results) {
  const key = [r.bench, r.runtime, r.model ?? "default", r.arm, r.checkpoint].join("\t");
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(r);
}

const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : null);
const fmt = (x, d = 0) => (x === null || Number.isNaN(x) ? "-" : x.toLocaleString("en-US", { maximumFractionDigits: d, minimumFractionDigits: d }));
const nums = (rs, f) => rs.map(f).filter((x) => typeof x === "number");

function extra(cp, rs) {
  if (cp === "cp1") {
    const caught = rs.filter((r) => r.score.testCatchesBug).length;
    return `test catches bug ${caught}/${rs.length}; src lines ${fmt(mean(nums(rs, (r) => r.score.diff?.srcLines)), 1)}`;
  }
  if (cp === "cp2-buggy") return `recall ${fmt(mean(nums(rs, (r) => r.score.recall)), 2)}`;
  return `false blocks ${fmt(mean(nums(rs, (r) => r.score.falseBlocks)), 2)}`;
}

const rows = [...groups.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([key, rs]) => {
  const [bench, runtime, model, arm, cp] = key.split("\t");
  const tokens = nums(rs, (r) => r.usage?.total);
  const cost = nums(rs, (r) => r.usage?.costUsd);
  const broken = rs.filter((r) => r.exitCode !== 0 || r.timedOut || !r.usage).length;
  return `| ${bench} | ${runtime} | ${model} | ${arm} | ${cp} | ${rs.length} | ${rs.filter((r) => r.score.pass).length}/${rs.length} | ${extra(cp, rs)} | ${tokens.length ? `${fmt(mean(tokens))} (${fmt(Math.min(...tokens))}-${fmt(Math.max(...tokens))})` : "-"} | ${cost.length ? `$${fmt(mean(cost), 3)}` : "-"} | ${fmt(mean(nums(rs, (r) => r.durationMs)) / 60000, 1)} | ${broken} |`;
});

writeFileSync(o.out, `# Bench results

Generated by \`node bench/report.mjs\` from the files in \`bench/results/\`.
Do not edit by hand. How the bench works and what each column means:
\`bench/README.md\`.

${rows.length === 0 ? "No results yet.\n" : `| Bench | Runtime | Model | Arm | Checkpoint | n | Pass | Detail | Tokens, mean (min-max) | Cost, mean | Minutes | Broken |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join("\n")}
`}`);
console.log(`${results.length} results, ${rows.length} rows -> ${relative(process.cwd(), o.out) || o.out}`);
